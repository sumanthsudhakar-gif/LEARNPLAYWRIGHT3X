//Ternary conditional statement is a shorthand way of writing an if-else statement. It takes three operands: a condition, a value to return if the condition is true, and a value to return if the condition is false. The syntax is as follows:
if (condition) {
  // code to execute if condition is true
} else {
  // code to execute if condition is false
// The ternary operator can be used to simplify this code into a single line:
condition ? valueIfTrue : valueIfFalse; }   

let age = 20;

let message = (age >= 18) ? "Eligible to vote" : "Not eligible to vote";

console.log(message);

